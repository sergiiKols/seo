# ─── Функции ───────────────────────────────────────────────────────────────

def humanize(text: str, style: str = 'neutral') -> str:
    """Основная функция очеловечивания."""

    # Замены — фразы в начале предложений
    sentence_starters = [
        ('В первую очередь', 'Сначала'),
        ('Прежде всего', 'Сначала'),
        ('Стоит отметить', ''),
        ('Необходимо отметить', ''),
        ('Важно учитывать', 'Нужно'),
        ('Следует учитывать', 'Надо'),
        ('Необходимо учитывать', 'Нужно'),
        ('Как известно', ''),
        ('Безусловно', ''),
        ('Разумеется', ''),
        ('Естественно', ''),
        ('Без сомнения', ''),
        ('Очевидно', ''),
        ('В современном мире', 'Сейчас'),
        ('На сегодняшний день', 'Сегодня'),
        ('В наши дни', 'Сегодня'),
        ('Таким образом', 'Поэтому'),
        ('В итоге', 'В итоге'),
        ('В конце концов', 'В итоге'),
        ('В результате', 'В итоге'),
        ('Кроме того', 'Ещё'),
        ('Помимо этого', 'Также'),
        ('Однако', 'Но'),
        ('Тем не менее', 'Но'),
        ('С другой стороны', 'А ещё'),
    ]

    # Заменяем фразы в начале предложений
    for phrase, replacement in sentence_starters:
        # Варианты: с запятой, с точкой, с пробелом
        patterns = [
            rf'{re.escape(phrase)},?\s+',
            rf'{re.escape(phrase)}\.\s+',
            rf'{re.escape(phrase)}\s+',
            rf'\({re.escape(phrase)}\)',
        ]
        for pattern in patterns:
            text = re.sub(pattern, replacement + ' ', text, flags=re.IGNORECASE)

    # Чистка: двойные пробелы
    text = re.sub(r'\s{2,}', ' ', text)

    # Чистка: несколько запятых подряд
    text = re.sub(r',\s*,', ',', text)

    # 2. Вариативность в числах
    text = vary_numbers(text)
    text = vary_numbers(text)

    # 3. Разбавляем повторы
    text = break_patterns(text)

    # 4. Стиль
    if style == 'casual':
        text = make_casual(text)
    elif style == 'formal':
        text = make_formal(text)

    # 5. Чистка
    text = clean_up(text)

    return text

def vary_numbers(text: str) -> str:
    """Заменяет ровные числа на варианты."""
    for num, variants in NUMBER_VARIANTS.items():
        # Целые числа в тексте
        pattern = rf'\b{num}\b'
        if re.search(pattern, text):
            # Заменяем не все, а через одного
            matches = list(re.finditer(pattern, text))
            for i, match in enumerate(matches):
                if i % 2 == 1:  # Каждое второе
                    replacement = random.choice(variants)
                    text = text[:match.start()] + replacement + text[match.end():]
    return text

def break_patterns(text: str) -> str:
    """Убирает повторяющиеся структуры."""

    # «во-первых, во-вторых» → «сначала, потом»
    text = re.sub(r'во-первых[,\s]+', 'сначала, ', text, flags=re.IGNORECASE)
    text = re.sub(r'во-вторых[,\s]+', 'потом, ', text, flags=re.IGNORECASE)
    text = re.sub(r'в-третьих[,\s]+', 'и ещё ', text, flags=re.IGNORECASE)

    # Убираем «1. 2. 3.» в конце предложений
    text = re.sub(r'\.(\s*[А-Я]\.)+', '.', text)

    # Пробелы между предложениями
    text = re.sub(r'\s{2,}', ' ', text)

    return text

def make_casual(text: str) -> str:
    """Делает текст неформальнее."""
    replacements = [
        (r'\bочень\b', ''),
        (r'\bдостаточно\b', ''),
        (r'\bдостаточно\s+важно', 'важно'),
        (r'\bвесьма\b', ''),
        (r'\bкрайне\b', ''),
        (r'\bчрезвычайно\b', ''),
        (r'\bневероятно\b', ''),
        (r'\bнеобходимо\b', 'надо'),
        (r'\bтребуется\b', 'нужно'),
        (r'\bВ\s+данный\s+момент\b', 'Сейчас'),
        (r'\bпо\s+данному\s+вопросу\b', 'тут'),
        (r'\bв\s+рамках\b', ''),
        (r'\bна\s+основе\b', 'по'),
        (r'\bс\s+учётом\b', 'учитывая'),
        (r'\bв\s+соответствии\s+с\b', 'по'),
        (r'\bне\s+говоря\s+уже\s+о\b', 'не говоря о'),
    ]
    for pattern, replacement in replacements:
        text = re.sub(pattern, replacement, text, flags=re.IGNORECASE)
    return text

def make_formal(text: str) -> str:
    """Делает текст формальнее."""
    replacements = [
        (r'\bмы\b', 'компания'),
        (r'\bнаш\b', 'наш'),
        (r'\bваш\b', 'ваш'),
    ]
    for pattern, replacement in replacements:
        text = re.sub(pattern, replacement, text, flags=re.IGNORECASE)
    return text

def clean_up(text: str) -> str:
    """Убирает лишние пробелы и артефакты."""
    # Убираем «, ,» и подобное
    text = re.sub(r'[,]{2,}', ',', text)
    text = re.sub(r'\s+', ' ', text)
    text = re.sub(r'\.\s+\.', '.', text)

    # Убираем «()» с пустотой
    text = re.sub(r'\(\s*\)', '', text)

    # Пробел перед точкой в конце
    text = re.sub(r'\s+\.', '.', text)

    # Убираем лидирующие запятые
    text = re.sub(r'^\s*,\s*', '', text)

    return text.strip()

# ─── CLI ─────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(description='Humanize Text — очеловечивание машинного текста')
    parser.add_argument('text', help='Текст или путь к .md файлу')
    parser.add_argument('--style', choices=['casual', 'formal', 'neutral'], default='neutral',
                       help='Стиль текста (по умолчанию: neutral)')
    parser.add_argument('--output', '-o', help='Сохранить в файл')
    args = parser.parse_args()

    # Читаем вход
    if args.text.startswith('http'):
        print("⚠️  URL не поддерживается — используйте curl для загрузки")
        sys.exit(1)

    if args.text.endswith('.md') or args.text.endswith('.txt'):
        try:
            with open(args.text, encoding='utf-8') as f:
                text = f.read()
            print(f"📄 Прочитан файл: {args.text}")
        except FileNotFoundError:
            print(f"❌ Файл не найден: {args.text}")
            sys.exit(1)
    else:
        text = args.text

    # Обрабатываем
    result = humanize(text, args.style)

    # Вывод
    print(f"\n{'='*60}")
    print(f"👤 РЕЗУЛЬТАТ (стиль: {args.style})")
    print(f"{'='*60}")
    print(result)

    if args.output:
        with open(args.output, 'w', encoding='utf-8') as f:
            f.write(result)
        print(f"\n✅ Сохранено: {args.output}")

if __name__ == '__main__':
    main()
