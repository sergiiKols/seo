# ─── Функции ───────────────────────────────────────────────────────────────

def stop_slop(text: str, strength: str = 'medium') -> str:
    """Убирает водянистость из текста."""

    # 1. Удаляем пустые фразы
    for pattern in DELETE_PHRASES:
        text = re.sub(pattern, '', text, flags=re.IGNORECASE)

    # 2. Сокращаем длинные фразы
    for pattern, replacement in SHORTEN_PHRASES:
        text = re.sub(pattern, replacement, text, flags=re.IGNORECASE)

    # 3. Агрессивный режим — дополнительные правила
    if strength == 'aggressive':
        text = aggressive_cleanup(text)
    elif strength == 'light':
        text = light_cleanup(text)

    # 4. Чистка
    text = cleanup(text)

    return text

def light_cleanup(text: str) -> str:
    """Лёгкая чистка — только самое очевидное."""
    # Убираем двойные пробелы
    text = re.sub(r'\s{2,}', ' ', text)
    # Пробелы перед пунктуацией
    text = re.sub(r'\s+([.,:;!?])', r'\1', text)
    return text

def aggressive_cleanup(text: str) -> str:
    """Агрессивная чистка."""
    # Удаляем скобки с пустотой
    text = re.sub(r'\([^)]*\b(?:и|в|на|по|за|для|к|о|у|с)\b[^)]*\)', '', text, flags=re.IGNORECASE)
    # Удаляем уточнения в скобках
    text = re.sub(r'\([^)]*\b(?:то есть|то бишь|иными словами|другими словами)\b[^)]*\)', '', text, flags=re.IGNORECASE)
    # Сокращаем причастные обороты
    text = re.sub(r',\s+который\s+', ', ', text, flags=re.IGNORECASE)
    text = re.sub(r',\s+которая\s+', ', ', text, flags=re.IGNORECASE)
    text = re.sub(r',\s+которые\s+', ', ', text, flags=re.IGNORECASE)
    return text

def cleanup(text: str) -> str:
    """Финальная чистка."""
    # Двойные пробелы
    text = re.sub(r'\s{2,}', ' ', text)
    # Пробелы перед пунктуацией
    text = re.sub(r'\s+([.,:;!?])', r'\1', text)
    # Пробелы после пунктуации
    text = re.sub(r'([.,:;!?])([А-Яа-яA-Za-z])', r'\1 \2', text)
    # Запятые с лишним
    text = re.sub(r',\s*,', ',', text)
    text = re.sub(r'\s*,\s*$', '', text)
    # Пустые скобки
    text = re.sub(r'\(\s*\)', '', text)
    # Точки сокращений (не трогаем)
    # Убираем лидирующие/конечные пробелы
    text = text.strip()
    # Несколько пустых строк
    text = re.sub(r'\n{3,}', '\n\n', text)
    return text

# ─── CLI ─────────────────────────────────────────────────────────────────────

def main():
    parser = argparse.ArgumentParser(description='Stop Slop — убирает водянистость из текста')
    parser.add_argument('text', help='Текст или путь к файлу')
    parser.add_argument('--strength', choices=['light', 'medium', 'aggressive'], default='medium',
                       help='Сила чистки (по умолчанию: medium)')
    parser.add_argument('--output', '-o', help='Сохранить в файл')
    args = parser.parse_args()

    # Читаем вход
    if args.text.endswith('.md') or args.text.endswith('.txt'):
        try:
            with open(args.text, encoding='utf-8') as f:
                text = f.read()
            print(f"📄 Прочитан файл: {args.text}")
        except FileNotFoundError:
            print(f"❌ Файл не найден: {args.text}")
            sys.exit(1)
    else:
        text = args.text

    # Обрабатываем
    result = stop_slop(text, args.strength)

    # Считаем сжатие
    original_words = len(text.split())
    result_words = len(result.split())
    ratio = (1 - result_words / original_words) * 100 if original_words > 0 else 0

    # Вывод
    print(f"\n{'='*60}")
    print(f"✂️  РЕЗУЛЬТАТ (сила: {args.strength})")
    print(f"{'='*60}")
    print(f"Сжато: {original_words} → {result_words} слов ({ratio:.0f}%)")
    print()
    print(result)

    if args.output:
        with open(args.output, 'w', encoding='utf-8') as f:
            f.write(result)
        print(f"\n✅ Сохранено: {args.output}")

if __name__ == '__main__':
    main()
