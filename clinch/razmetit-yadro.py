#!/usr/bin/env python3
"""Разметка пригодности пересобранного ядра clinch.by.

Правило мастерской: объём кластера ничего не значит, пока не разделён по
намерению. Сырой съём даёт 31 401 показ, но внутри — мем про сову на
скакалке, шампунь «Скин-кап», капы от храпа и ТВ-приставки.

Умолчание здесь ОБРАТНОЕ обычному: фраза считается нашей, только если в ней
есть товарный маркер из ассортимента. Не доказана — уходит в «спорное»
на ручной просмотр, а не в ядро.

  наше    — есть товарный маркер, нет стоп-слова;
            для многозначных слов («скакалка», «капа») дополнительно нужен
            ТЕМАТИЧЕСКИЙ уточнитель: бокс, спорт, тренировка, бренд.
            «Купить» уточнителем не считается — капу покупают и от храпа;
  спорное — товарного маркера нет либо многозначное слово без уточнителя;
  чужое   — стоп-лист: другой товар, другое гео, не покупка.
"""
import csv, re, collections
from datetime import date

SRC = "/root/seo/clinch/yadro-clinch-2026-08-19.csv"
TODAY = date.today().isoformat()

# 1. Жёсткие отклонения — другой товар, другое гео, не покупка
STOP = [
    ("мем и игры",          r"(сова|сава|мем|прикол|что значит|карточка|карта на скакалке|мод на|день скакалк|порка)"),
    ("шампунь «Скин-кап»",  r"скин.?кап"),
    ("аптека: храп, зубы, крем", r"(храп|зуб|стоматолог|выравниван|прикус|брекет|аптек|крем|мазь|псориаз|гиалурон)"),
    ("ТВ-приставки",        r"(тв.?бокс|андроид|android|приставк|smart\s?tv)"),
    ("не наш ассортимент",  r"(спортивн\w* питани|протеин|креатин|гейнер|спортивных костюмов|спортивной обуви|велосипед)"),
    ("художественная гимнастика", r"(пасторелли|pastorelli|sasaki|саsaki|chacott|гимнастическ|художественн)"),
    ("чужое гео",           r"(москв|россии|россия|санкт|спб|киев|украин|казахстан|алматы|екатеринбург|ростов|новосибирск|краснодар|казан|самар|воронеж|сочи)"),
    ("вторичка и пиратство",r"(авито|куфар|\bбу\b|б/у|бесплатно|скачать|торрент)"),
    ("не покупка",          r"(порно|обои|тату|рисунок|нарисовать|игра|видео|как сделать|своими руками|похуде|калори|сколько прыгать)"),
    ("одежда, не обувь",    r"(майка борцовка|майка боксерка|борцовка мужская|борцовка женская|борцовк[аи] женск)"),
]
# 2. Товарные маркеры ассортимента (12 категорий магазина)
TOVAR = r"""(перчатк|шлем|бинт|лап[аыу]\b|макивар|мешок|мешк|груш|борцовк|боксерк|
             шорт|майк|футболк|трус[ыа]|форм[аыу]|экипировк|снаряд|защит|бандаж|ракушк|
             скакалк|кап[аыу]\b|\bкап\b|clinch|клинч)"""
TOVAR = re.compile(TOVAR.replace("\n", "").replace(" ", ""))
# 3. Многозначные слова — нужен уточнитель
AMBIG = re.compile(r"(скакалк|кап[аыу]\b|\bкап\b)")
# Уточнитель для многозначного слова должен быть ТЕМАТИЧЕСКИМ. «Купить» не
# уточняет: «капа купить» — это с равным успехом капа от храпа. Коммерческие
# маркеры сюда намеренно не входят.
QUALIF = re.compile(r"(бокс|борьб|единоборст|спорт|тренир|clinch|клинч|"
                    r"скоростн|утяжел|кожан|гелев|термопласт)")


# ── Проверка соседства 19.08.2026 ────────────────────────────────────────────
# Спорные фразы разрешены не на глаз, а по их собственной таблице Wordstat в
# регионе 149: что люди ищут ВМЕСТЕ с этими словами. Выдачу поисковика с этой
# машины снять не удалось (Яндекс — капча, Google — требует JS, Bing отдаёт
# чужой кэш), поэтому взят второй надёжный сигнал — данные самого Яндекса.
PROVERENO = [
    # (регулярка, оценка, причина)
    (r"^(капа|капу|кап)\b(?!.*(бокс|борьб|единоборст|спорт|clinch|клинч))",
     "чужое", "проверено 19.08: соседи — «скин-кап» (шампунь), капы для зубов и от храпа; бокса 0%"),
    (r"(?<!боксерск )кап[ауы]? купить|купить кап\b|купить капу минск",
     "чужое", "проверено 19.08: в кластере 4 215 показов бокса 0%, аптеки 41%"),
    (r"^скакалка$|^со скакалкой$|прыжки на скакалке|как прыгать|скакалка сколько|можно скакалка|скакалка правильно",
     "чужое", "проверено 19.08: в кластере «скакалка» 33% мем «сова на скакалке», 13% фитнес-вопросы, покупка 1%"),
    (r"скакалк\w* купить|купить скакалк|скакалка минск|скакалк\w* в минске",
     "наше", "проверено 19.08: в кластере «скакалка купить» 89% покупка, в «скакалка минск» мема нет"),
    # Хвост кластера «скакалка» без товарного или гео-уточнения: по замеру
    # 19.08 в этом кластере покупка — 1%, остальное мем и фитнес-вопросы.
    (r"скакалк(?!.*(купить|цена|стоимост|минск|магазин|заказ|доставк|скоростн|утяжел|кожан|спортивн|детск|бокс|clinch|клинч))",
     "чужое", "проверено 19.08: информационный и мем-хвост кластера «скакалка», покупка в нём 1%"),
    (r"магазин\w*.*(одежд|обув|питани|костюм|тренажер|инвентар|бад)",
     "чужое", "проверено 19.08: магазин другого ассортимента, не экипировки"),
    (r"^(?!.*(питани|костюм|обув|одежд|гиалурон|велосип|тренажер|инвентар)).*(спортивн\w* магазин\w*|магазин\w* спортивн)",
     "главная", "проверено 19.08: соседи — одежда, обувь, спортпитание, костюмы; запрос уровня магазина, не категории"),
]
PROVERENO = [(re.compile(rx), g, why) for rx, g, why in PROVERENO]

def grade(p):
    low = p.lower()
    for why, rx in STOP:
        if re.search(rx, low): return "чужое", why
    for rx, g, why in PROVERENO:
        if rx.search(low): return g, why
    if not TOVAR.search(low):
        return "спорное", "нет товарного маркера"
    if AMBIG.search(low) and not QUALIF.search(low):
        return "спорное", "многозначное слово без уточнителя"
    return "наше", ""

rows = list(csv.DictReader(open(SRC, encoding="utf-8"), delimiter=";"))
for r in rows:
    r["Пригодность"], r["Причина"] = grade(r["Ключевое слово"])
cols = list(rows[0].keys())

def dump(name, rs):
    with open(f"/root/seo/clinch/{name}", "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols, delimiter=";"); w.writeheader()
        w.writerows(sorted(rs, key=lambda r: -int(r["Частота Yandex"])))

nash = [r for r in rows if r["Пригодность"] in ("наше", "главная")]
dump(f"yadro-clinch-razmechennoe-{TODAY}.csv", rows)
dump(f"yadro-clinch-rabochiy-{TODAY}.csv", nash)

def s(rs): return sum(int(r["Частота Yandex"]) for r in rs)
print(f"сырой съём:   {len(rows):>5} фраз, {s(rows):>7,} показов")
for g in ("наше", "главная", "спорное", "чужое"):
    sub = [r for r in rows if r["Пригодность"] == g]
    print(f"  {g:<9} {len(sub):>5} фраз, {s(sub):>7,} показов ({s(sub)*100//s(rows)}%)")
print("\nпочему отклонено или отложено:")
for why, n in collections.Counter(r["Причина"] for r in rows
                                  if r["Причина"] and r["Пригодность"] != "наше").most_common():
    sub = [r for r in rows if r["Причина"] == why]
    print(f"  {why:<38} {n:>4} фраз, {s(sub):>6,} показов")
print("\nрабочий срез по категориям:")
agg = collections.defaultdict(lambda: [0, 0])
for r in nash:
    a = agg[r["Категория"]]; a[0] += 1; a[1] += int(r["Частота Yandex"])
for c, (n, v) in sorted(agg.items(), key=lambda x: -x[1][1]):
    print(f"  {c:<24} {n:>4} фраз, {v:>7,} показов")
