#!/usr/bin/env python3
"""Загрузка замеров SEO в memora.

Каждый замер — отдельный факт с датой и методом, чтобы при повторном
замере образовалась цепочка версий, а не перезапись. Это и есть причина,
по которой memora поставлена на этот участок.
"""
import csv, json, sys
sys.path.insert(0, '/root/seo/.memora-venv/lib/python3.12/site-packages')
from memora import storage

BASE = '/root/seo/ideav-ru/kb-2026-08-18'
DATE = '2026-08-18'
conn = storage.connect(); storage.ensure_schema(conn)

added = {'замер': 0, 'кластер': 0, 'отклонено': 0, 'правило': 0, 'решение': 0}


def put(content, tags, meta=None):
    storage.add_memory(conn, content=content, tags=tags, metadata=meta or {})


# 1. Замеренные частоты фраз (источник «замер 18.08»)
with open(f'{BASE}/keywords-tracking.csv', encoding='utf-8') as f:
    for row in csv.DictReader(f, delimiter=';'):
        if row.get('источник_частоты') != 'замер 18.08':
            continue
        ph = (row.get('ключевое слово') or '').strip()
        if not ph:
            continue
        freq = (row.get('частота') or '').strip() or 'нет числа'
        put(
            f"Частота Яндекса по фразе «{ph}» — {freq}. Замер Wordstat {DATE}, "
            f"регион «все», метод table. Целевая страница: {row.get('страница')} "
            f"({row.get('url')}). Роль: {row.get('роль')}. Намерение: {row.get('намерение')}. "
            f"Статус внедрения: {row.get('статус')}.",
            tags=['seo/замер', 'seo/ideav-ru'],
            meta={'фраза': ph, 'частота': freq, 'дата_замера': DATE,
                  'метод': 'wordstat table, регион все', 'url': row.get('url')},
        )
        added['замер'] += 1

# 2. Кластеры целиком (голова + сумма)
with open(f'{BASE}/wordstat-dobor.json', encoding='utf-8') as f:
    for it in json.load(f):
        if not it.get('rows'):
            continue
        put(
            f"Кластер «{it['phrase']}»: голова {it['head']}, фраз в кластере {it['rows']}, "
            f"суммарная частота {it['cluster_sum']}. Замер Wordstat {DATE}. "
            f"ВАЖНО: сумма кластера — не наш спрос, её обязательно делить по намерению.",
            tags=['seo/кластер', 'seo/ideav-ru'],
            meta={'затравка': it['phrase'], 'голова': it['head'],
                  'сумма_кластера': it['cluster_sum'], 'дата_замера': DATE},
        )
        added['кластер'] += 1

# 3. Отклонённые кластеры — защита от повторного захода
otkloneno = [
    ("сводные таблицы", 228489, "99,9% — обучение работе со сводной таблицей в Excel"),
    ("сводная таблица", 64720, "обучение Excel: для чайников, пошаговая инструкция, шаблон скачать"),
    ("ии агент", 59767, "94% — разработчики агентов и новостной шум, не заказчики"),
    ("впр excel (обучающая часть)", 58903, "человек хочет научиться пользоваться ВПР, а не заменить её"),
    ("отчет по продажам", 58056, "кластер учётной системы и 1С, а не отчёт вместо BI"),
    ("форма заявки", 22354, "бумажный бланк для тендера и госзакупки"),
    ("поиск по документам", 20308, "90% — Ctrl+F, архивы, суды"),
    ("сводные таблицы excel", 15644, "обучение Excel"),
    ("полнотекстовый поиск", 15033, "1С-эксплуатация; механизм, которому статья прямо противопоставлена"),
    ("информационная система и сопровождение", 14819, "дословное название специальности СПО, учебный трафик"),
    ("нейросеть для бизнеса", 4913, "курсы и генерация бизнес-планов, наших менее 200"),
    ("сопоставление каталогов", 0, "слово мёртвое: рынок говорит «номенклатура» и «товары»"),
]
for ph, freq, why in otkloneno:
    put(
        f"ОТКЛОНЁН кластер «{ph}» ({freq} показов): {why}. Решение принято {DATE} "
        f"после разбора по намерению. Не предлагать повторно без новых доводов.",
        tags=['seo/отклонено', 'seo/ideav-ru'],
        meta={'кластер': ph, 'частота': freq, 'дата_решения': DATE},
    )
    added['отклонено'] += 1

# 4. Правила, выведенные работой
pravila = [
    ("Объём кластера ничего не значит, пока не разделён по намерению. "
     "Проверено трижды: у ВПР из 65 068 нашими оказались 2 838; у Airtable из 2 499 — 172; "
     "у реестра отечественного ПО из 15 777 — 1 308."),
    ("Вердикт «фразы нет в семантическом ядре» запрещён как основание для вывода. "
     "Все три статьи, признанные бесперспективными по этому основанию (08a, 20, 21), "
     "при прямом замере Wordstat оказались перспективными."),
    ("Файлу keywords_all.csv нельзя верить: он подводит тремя способами — строк нет вовсе "
     "(впр excel 16 284, вайб кодинг 14 907), числа занижены (on premise 2 против 2 827), "
     "числа завышены широким соответствием (система автоматизации отчетности 699 против 156). "
     "Сдвиг разнонаправленный, единого коэффициента пересчёта не существует."),
    ("Каждое число живёт с датой и методом замера. «Система управления заявками» дала "
     "594 и 378 в один и тот же день при разных замерах."),
    ("Заголовок на ideav.ru собирается так: <title> = seoTitle, если он заполнен И его длина "
     "не больше 60 символов; иначе shortTitle + « — Интеграм». Сверено по всем 27 страницам "
     "базы знаний. Правило выведено с третьей попытки: первые две проверялись на неполной выборке."),
    ("Авторы называют вещи своими словами, рынок ищет чужими: в статье про заявки слово «учёт» "
     "встречается ноль раз, в статье про семантический поиск «семантическ» — ноль. "
     "Решение — не переписывать авторский язык, а один раз ввести рыночный термин определением."),
]
for p in pravila:
    put(p, tags=['seo/правило', 'seo/ideav-ru'], meta={'дата': DATE})
    added['правило'] += 1

# 5. Отложенное решение
put(
    "ОТЛОЖЕНО 18.08.2026: 12 отраслевых страниц ideav.ru (crm-uchet-klientov, skladskoy-uchet, "
    "finansovyy-uchet, kadrovyy-uchet, uchet-dogovorov, upravlencheskiy-uchet, upravlenie-zakupkami, "
    "planirovanie-proizvodstva, baza-zayavok, dvizhenie-tmc-i-ds, upravlenie-proektami, resheniya). "
    "Под ними крупнейший измеренный кластер — язык учёта, 1 094 154 показа. Все озаглавлены "
    "«X вместо Excel», то есть под кластер замены Excel (2 981), который в тридцать раз меньше. "
    "Ни замера, ни оптимизации, ни строки в трекинг-листе. Взять следующим этапом. "
    "Перед стартом обязателен ручной разбор по намерению: внутри сидят регистрация автомобилей "
    "(учет договоров купли продажи, 29 086) и военкомат (воинский учет).",
    tags=['seo/решение', 'seo/ideav-ru', 'seo/отложено'], meta={'дата': DATE, 'приоритет': 1})
added['решение'] += 1

conn.commit()
print("Загружено:", ", ".join(f"{k} {v}" for k, v in added.items()))
print("Всего фактов:", sum(added.values()))
